// pickOptions — n случайных мест из списка (порядок тоже случайный).
func pickOptions(places []string, n int) []string {
	p := append([]string(nil), places...)
	rand.Shuffle(len(p), func(i, j int) { p[i], p[j] = p[j], p[i] })
	if len(p) > n {
		p = p[:n]
	}
	return p
}
